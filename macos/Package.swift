// swift-tools-version:5.9
import PackageDescription

let package = Package(
    name: "JSpiceMac",
    platforms: [.macOS(.v14)],
    products: [
        .executable(name: "JSpice", targets: ["JSpice"]),
        .executable(name: "jspice-mcp", targets: ["jspice-mcp"]),
        .executable(name: "JSpiceAudioUnit", targets: ["JSpiceAudioUnit"]),
        .library(name: "CircuitKit", targets: ["CircuitKit"]),
        .library(name: "KiCadKit", targets: ["KiCadKit"]),
        .library(name: "KiCadLink", targets: ["KiCadLink"]),
        .library(name: "JSpiceAutomation", targets: ["JSpiceAutomation"]),
    ],
    dependencies: [
        // KiCad's API speaks protocol buffers (KiCadLink's messages are generated from KiCad's own .proto files)
        .package(url: "https://github.com/apple/swift-protobuf.git", exact: "1.38.1"),
    ],
    targets: [
        // The simulation engine and circuit model. No UI code, so it can be unit tested on its own.
        // Release builds skip Swift's run-time exclusivity checks in the engine: its inner loops touch the simulator's
        // arrays millions of times a second (one step per audio sample with sound on), and the checks cost more than
        // the arithmetic. Debug builds and tests keep them.
        .target(name: "CircuitKit", dependencies: ["CortexM4", "KiCadKit"],
                swiftSettings: [.unsafeFlags(["-enforce-exclusivity=unchecked"], .when(configuration: .release))]),
        // An ARM Cortex-M4 core (with its FPU and system control space) in C, for the STM32 parts: an interpreter that is
        // optimized even in debug builds, as tests run firmware on it.
        // (stm32_pins.inc: a table stm32.c includes, generated by tools/arm-reference/pinmap.py)
        .target(name: "CortexM4", exclude: ["stm32_pins.inc"], cSettings: [.unsafeFlags(["-O2"])]),
        // KiCad's boards, footprint libraries and tools: boards read and written as KiCad writes them, a board brought
        // up to date with the schematic as KiCad's own netlist updater does, kicad-cli for checks and fabrication files.
        // Foundation only, so that it builds on Linux too, where CI checks it against KiCad itself.
        .target(name: "KiCadKit"),
        // KiCad's PCB editor while it runs, through KiCad's API (its protobuf messages over a local NNG socket): the board
        // kept up to date with the schematic as one undoable change, the editors' selections followed both ways.
        // (Generated: KiCad 10.0.7's API messages, made by tools/kicad-api/generate.sh)
        .target(name: "KiCadLink", dependencies: ["KiCadKit", .product(name: "SwiftProtobuf", package: "swift-protobuf")]),
        // Tools for driving circuits from outside: netlists, simulation runs, measurements, and an MCP server for AI agents.
        .target(name: "JSpiceAutomation", dependencies: ["CircuitKit"]),
        // The MCP server on standard input and output.
        .executableTarget(name: "jspice-mcp", dependencies: ["JSpiceAutomation", "CircuitKit"]),
        // The Audio Unit (an app extension inside the app): a circuit as an effect or instrument in any music app. Its
        // process starts in NSExtensionMain, which loads the principal class named in its Info.plist.
        .executableTarget(name: "JSpiceAudioUnit", dependencies: ["CircuitKit"],
                          linkerSettings: [.unsafeFlags(["-Xlinker", "-e", "-Xlinker", "_NSExtensionMain"])]),
        // The macOS app.
        .executableTarget(name: "JSpice", dependencies: ["CircuitKit", "JSpiceAutomation"]),
        .testTarget(name: "CircuitKitTests", dependencies: ["CircuitKit", "CortexM4", "KiCadKit"], resources: [.copy("Fixtures")]),
        .testTarget(name: "JSpiceAutomationTests", dependencies: ["JSpiceAutomation", "CircuitKit"]),
        .testTarget(name: "KiCadKitTests", dependencies: ["KiCadKit"], resources: [.copy("Fixtures")]),
        .testTarget(name: "KiCadLinkTests", dependencies: ["KiCadLink", "KiCadKit"]),
    ]
)
